import { mkdir, readFile, writeFile } from "node:fs/promises";
import { generateAssetKey, sealAsset } from "@pexserver/secure-envelope/asset";

const application = await Bun.build({
  entrypoints: ["src/React/index.tsx"],
  minify: true,
  target: "browser",
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!application.success) {
  console.error(application.logs);
  process.exit(1);
}
const bootstrap = await Bun.build({
  entrypoints: ["src/React/bootstrap.ts"],
  minify: true,
  target: "browser",
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!bootstrap.success) {
  console.error(bootstrap.logs);
  process.exit(1);
}
const applicationJs = await application.outputs.find((o) => o.path.endsWith(".js"))!.text();
const bootstrapJs = await bootstrap.outputs.find((o) => o.path.endsWith(".js"))!.text();
const shadowCss = (await readFile("public/theme.css", "utf8"))
  .replace(/:root/g, ":host")
  .replace(/\bbody\b/g, ":host");
const browserAssetKey = generateAssetKey();
const browserAssetContext = `fileshare-browser:${crypto.randomUUID()}`;
const encryptedApplication = await sealAsset(
  applicationJs,
  browserAssetKey,
  browserAssetContext,
);
const encryptedStyle = await sealAsset(
  shadowCss,
  browserAssetKey,
  browserAssetContext + ":style",
);
const html =
  '<!doctype html><html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="description" content="PEXserverの共有ストレージ。パスキーで安全にファイルを共有。"><title>FileShare | PEXserver</title><link rel="icon" href="/server.png"></head><body><script type="module" src="/index.js"></script></body></html>';
await writeFile("public/index.html", html);
await writeFile("public/index.js", bootstrapJs);
await writeFile("public/app.bin", encryptedApplication);
await writeFile("public/style.bin", encryptedStyle);
const files = [
  ["/index.html", "text/html; charset=utf-8"],
  ["/index.js", "application/javascript; charset=utf-8"],
  ["/app.bin", "application/octet-stream"],
  ["/style.bin", "application/octet-stream"],
  ["/theme.css", "text/css; charset=utf-8"],
  ["/server.png", "image/png"],
  ["/fonts/plus-jakarta-sans-latin-v12.woff2", "font/woff2"],
  ["/fonts/space-grotesk-latin-700-v22.woff2", "font/woff2"],
  ["/fonts/PlusJakartaSans-OFL.txt", "text/plain; charset=utf-8"],
  ["/fonts/SpaceGrotesk-OFL.txt", "text/plain; charset=utf-8"],
];
const assets: Record<string, { type: string; body: string }> = {};
for (const [name, type] of files)
  assets[name] = {
    type,
    body: (await readFile("public" + name)).toString("base64"),
  };
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/v2assets.ts",
  "// Generated by bun run build\n" +
    `export const BROWSER_ASSET_KEY=${JSON.stringify(browserAssetKey)};\n` +
    `export const BROWSER_ASSET_CONTEXT=${JSON.stringify(browserAssetContext)};\n` +
    "export const ASSETS: Record<string, {type: string; body: string}> = " +
    JSON.stringify(assets) +
    ";\n",
);
if (process.argv.includes("--exe")) {
  const server = await Bun.build({
    entrypoints: ["src/index.ts"],
    target: "bun",
    outdir: "dist",
    naming: "server.js",
    minify: true,
  });
  if (!server.success) {
    console.error(server.logs);
    process.exit(1);
  }
}
console.log("Built PEXserver FileShare UI and embedded assets.");
