import { mkdir, readFile, writeFile } from "node:fs/promises";
const result = await Bun.build({
  entrypoints: ["src/React/index.tsx"],
  minify: true,
  target: "browser",
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!result.success) {
  console.error(result.logs);
  process.exit(1);
}
const js = await result.outputs.find((o) => o.path.endsWith(".js"))!.text();
const html =
  '<!doctype html><html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="description" content="PEXserverの共有ストレージ。パスキーで安全にファイルを共有。"><title>FileShare | PEXserver</title><link rel="icon" href="/server.png"><link rel="stylesheet" href="/theme.css"></head><body><div id="root"></div><script type="module" src="/index.js"></script></body></html>';
await writeFile("public/index.html", html);
await writeFile("public/index.js", js);
const files = [
  ["/index.html", "text/html; charset=utf-8"],
  ["/index.js", "application/javascript; charset=utf-8"],
  ["/theme.css", "text/css; charset=utf-8"],
  ["/server.png", "image/png"],
  ["/fonts/plus-jakarta-sans-latin-v12.woff2", "font/woff2"],
  ["/fonts/space-grotesk-latin-700-v22.woff2", "font/woff2"],
  ["/fonts/PlusJakartaSans-OFL.txt", "text/plain; charset=utf-8"],
  ["/fonts/SpaceGrotesk-OFL.txt", "text/plain; charset=utf-8"],
];
const assets: Record<string, { type: string; body: string }> = {};
for (const [name, type] of files)
  assets[name] = {
    type,
    body: (await readFile("public" + name)).toString("base64"),
  };
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/v2assets.ts",
  "// Generated by bun run build\nexport const ASSETS: Record<string, {type: string; body: string}> = " +
    JSON.stringify(assets) +
    ";\n",
);
if (process.argv.includes("--exe")) {
  const server = await Bun.build({
    entrypoints: ["src/index.ts"],
    target: "bun",
    outdir: "dist",
    naming: "server.js",
    minify: true,
  });
  if (!server.success) {
    console.error(server.logs);
    process.exit(1);
  }
}
console.log("Built PEXserver FileShare UI and embedded assets.");
